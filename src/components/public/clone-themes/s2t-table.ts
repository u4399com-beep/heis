// 构建简→繁 map (后者覆盖前者, 去重)
export const S2T_MAP: Record<string, string> = (() => {
  const m: Record<string, string> = {}
  for (const [s, t] of S2T_PAIRS) {
    if (s.length === 1) m[s] = t
    else if (s.length > 1) {
      // 多字词: 仅当能整体替换时用 (这里全部展开为单字)
      for (let i = 0; i < s.length; i++) {
        if (!m[s[i]]) m[s[i]] = t[i] ?? s[i]
      }
    }
  }
  return m
})()

// 反向 map: 繁→简 (单字反向, 多对一时取最后一个)
export const T2S_MAP: Record<string, string> = (() => {
  const m: Record<string, string> = {}
  for (const [s, t] of Object.entries(S2T_MAP)) {
    m[t] = s
  }
  return m
})()

// 简体 → 繁体: 单字替换
export function s2t(text: string): string {
  if (!text) return text
  let out = ''
  for (const ch of text) {
    out += S2T_MAP[ch] ?? ch
  }
  return out
}

// 繁体 → 简体: 单字反向替换
export function t2s(text: string): string {
  if (!text) return text
  let out = ''
  for (const ch of text) {
    out += T2S_MAP[ch] ?? ch
  }
  return out
}
